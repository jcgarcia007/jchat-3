// Guards the web icon alias (metro.config.js → web-stubs/tabler-icons.web.ts). Run from mobile/:
//   node --test scripts/tabler-icons.test.mjs

import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { collectIcons, isStale } from './gen-tabler-icons.mjs';

const STUB = fileURLToPath(new URL('../web-stubs/tabler-icons.web.ts', import.meta.url));
const PKG_ICONS = fileURLToPath(new URL('../node_modules/@tabler/icons-react-native/dist/esm/icons/', import.meta.url));

test('every icon imported in the code is exported by the generated web module', () => {
  const { icons, problems } = collectIcons();
  assert.deepEqual(problems, [], 'imports the generator cannot analyse');
  assert.ok(existsSync(STUB), 'web-stubs/tabler-icons.web.ts is missing: run node scripts/gen-tabler-icons.mjs');
  const exported = new Set([...readFileSync(STUB, 'utf8').matchAll(/export \{ default as (\w+) \}/g)].map((m) => m[1]));
  const missing = icons.filter((name) => !exported.has(name));
  assert.deepEqual(missing, [], 'icons missing from the generated file: run node scripts/gen-tabler-icons.mjs');
});

test('the generated file is up to date (no stale extras, sorted, header)', () => {
  assert.equal(isStale(), false, 'out of date: run node scripts/gen-tabler-icons.mjs');
  assert.match(readFileSync(STUB, 'utf8'), /GENERATED by scripts\/gen-tabler-icons\.mjs — DO NOT EDIT/);
});

test('every re-exported icon exists as its own file in the installed package', () => {
  const names = [...readFileSync(STUB, 'utf8').matchAll(/export \{ default as (\w+) \}/g)].map((m) => m[1]);
  assert.ok(names.length > 0);
  assert.deepEqual(names, [...names].sort());
  for (const name of names) assert.ok(existsSync(`${PKG_ICONS}${name}.mjs`), `${name}.mjs not found in the package`);
});
