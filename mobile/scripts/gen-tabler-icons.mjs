// Generates web-stubs/tabler-icons.web.ts: the web build of '@tabler/icons-react-native' re-exports ONLY the
// icons the code imports (each from its own file: the package's "./*" export maps to dist/esm/icons/*.mjs), so
// Metro does not bundle all ~6000 icons. iOS / Android keep using the full package.
//   node scripts/gen-tabler-icons.mjs          → rewrites the file
//   node scripts/gen-tabler-icons.mjs --check  → exit 1 if the file is out of date (used by the test)
// Fails (exit 2) on an import form it cannot analyse statically (namespace import, require, dynamic import).

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'web-stubs', 'tabler-icons.web.ts');
const PKG = '@tabler/icons-react-native';
const SKIP_DIRS = new Set(['node_modules', 'ios', 'android', 'web-stubs', '.expo', '.git']);
const CODE = /\.(ts|tsx|js|jsx|mjs)$/;

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name) || name.startsWith('dist')) continue;
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) yield* walk(full);
    else if (CODE.test(name) && !name.endsWith('.d.ts')) yield full;
  }
}

/** Icon names imported (as values) from the package across mobile/, plus the problems found. */
export function collectIcons(root = ROOT) {
  const icons = new Set();
  const problems = [];
  const named = new RegExp(`import\\s+(type\\s+)?\\{([^}]*)\\}\\s*from\\s*['"]${PKG}['"]`, 'g');
  const mention = new RegExp(`['"]${PKG}['"]`);
  for (const file of walk(root)) {
    if (/(gen-tabler-icons\.mjs|tabler-icons\.test\.mjs|metro\.config\.js)$/.test(file)) continue;
    const src = readFileSync(file, 'utf8');
    if (!mention.test(src)) continue;
    const rest = src.replace(named, (_all, isType, body) => {
      if (!isType) {
        for (const part of body.split(',')) {
          const spec = part.trim();
          if (!spec || /^type\s/.test(spec)) continue;
          icons.add(spec.split(/\s+as\s+/)[0].trim());
        }
      }
      return '';
    });
    if (mention.test(rest)) problems.push(`${relative(root, file)}: import form not statically analysable`);
  }
  return { icons: [...icons].sort(), problems };
}

export function renderStub(icons) {
  const lines = icons.map((name) => `export { default as ${name} } from '${PKG}/${name}';`);
  return [
    '// @ts-nocheck — the package ships no types for its per-icon subpaths; importers type against the real package.',
    '// GENERATED by scripts/gen-tabler-icons.mjs — DO NOT EDIT. Run: node scripts/gen-tabler-icons.mjs',
    `// Web-only replacement for '${PKG}' (see metro.config.js): only the icons the code uses,`,
    '// each from its own file, so the web bundle does not carry the whole icon set.',
    '',
    ...lines,
    '',
  ].join('\n');
}

export function isStale(root = ROOT) {
  const { icons } = collectIcons(root);
  return !existsSync(OUT) || readFileSync(OUT, 'utf8') !== renderStub(icons);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { icons, problems } = collectIcons();
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(2);
  }
  const text = renderStub(icons);
  if (process.argv.includes('--check')) {
    process.exit(existsSync(OUT) && readFileSync(OUT, 'utf8') === text ? 0 : 1);
  }
  writeFileSync(OUT, text);
  console.log(`${icons.length} icons → ${relative(ROOT, OUT)}`);
}
